import sharp from "sharp";
import fs from "fs";
import * as mupdf from "mupdf";
const D = "../docs/source-pdf/extracted/";
const f = ["company-profile-p02-145", "company-profile-p07-112", "product-profile-p09-71", "product-profile-p01-150", "product-profile-p07-56", "product-profile-p07-58"];
const W = 400, H = 300;
const tiles = await Promise.all(f.map((n) => sharp(D + n + ".png").resize(W, H, { fit: "contain", background: "#ff00ff" }).flatten({ background: "#ff00ff" }).toBuffer()));
await sharp({ create: { width: W * 3, height: H * 2, channels: 3, background: "#000" } }).composite(tiles.map((t, i) => ({ input: t, left: (i % 3) * W, top: Math.floor(i / 3) * H }))).jpeg().toFile("../.check.jpg");
const doc = new mupdf.PDFDocument(fs.readFileSync("../docs/source-pdf/company-profile.pdf"));
const res = doc.loadPage(2).getObject().get("Resources");
res.forEach((v, k) => console.log(k, v.resolve().toString().slice(0, 300)));
